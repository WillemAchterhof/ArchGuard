#!/usr/bin/env bash

# ==============================================================================
#  ArchGuard Modules
# ==============================================================================
#  orchestrator/load-modules.sh
#
#  Provides the entry point for loading and executing ArchGuard modules.
# ==============================================================================

# ==============================================================================
# Module Loader
# ==============================================================================

load_module() {
    local module_name="$1"

    run_module "$module_name"
    "run_$module_name"
}
